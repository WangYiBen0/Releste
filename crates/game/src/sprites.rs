//! Entity -> sprite lookup table, and the rules for cutting a tileset image into 8x8 cells.
//!
//! # Why this table is needed
//! The engine core carries no gameplay (AGENTS.md 4.1), but **rendering** a ready-made `.map`
//! needs to know which image to take. The real answer is eventually registered by plugins through capabilities
//! (ROADMAP Phase 3); this is the minimal built-in table that gets 0-Intro running,
//! and every entity that misses it is `tracing::warn` + skipped (AGENTS.md 15.8 / 15.9).

use std::collections::HashMap;

use releste_render::atlas::{Sprite, SpriteAtlas, TextureGroup};

/// World pixel size of one tile. Room `lvl_-1` is 320 wide / 40 cells = 8px.
pub const TILE_PX: i32 = 8;

/// Built-in entity sprite table.
///
/// An entity with no entry is not an error: `wire` is a line segment and `introCrusher` is a
/// tile grid generated by the autotiler; both are drawn separately by `session`.
pub fn entity_sprite(kind: &str) -> Option<&'static str> {
    Some(match kind {
        // `player` is drawn separately by the simulation each frame and does not go into the static batch.
        // `introCrusher` is not in the table: it has no crushblock texture and its look is
        // `GFX.FGAutotiler.GenerateBox('3', w/8, h/8)` (106322).
        "lamp" => "scenery\\lamp",
        "flutterbird" => "scenery\\flutterbird\\idle00",
        // The start animation of vanilla `GFX.SpriteBank.Create("bird")` is `idle`,
        // whose path is `crow` (Sprites.xml:261-263) -> the idle frame `crow00`,
        // not `Recover00` (that plays only after getting hit).
        "bird" => "characters\\bird\\crow00",
        "introCar" => "scenery\\car\\body",
        "introCarWheels" => "scenery\\car\\wheels",
        _ => return None,
    })
}

